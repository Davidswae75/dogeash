// Writes supabase/seed.sql from the app's sample stores and dogs, so the database starts with
// the same marketplace the site shows today. Run with `npm run db:seed`. Development data only.
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { basename, join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { build } from 'esbuild'

const root = resolve(import.meta.dirname, '..')
const dir = mkdtempSync(join(tmpdir(), 'dogeash-seed-'))
const outfile = join(dir, 'data.mjs')

await build({
  stdin: { contents: `export { sampleStores } from './app/utils/stores'\nexport { sampleDogs } from './app/utils/dogs'`, resolveDir: root, loader: 'ts' },
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile,
  logLevel: 'silent',
  alias: { '@': join(root, 'app'), '~': join(root, 'app') },
  plugins: [{
    // Photos become their storage path instead of a bundled file
    name: 'photo-paths',
    setup(b) {
      b.onLoad({ filter: /\.(jpe?g|png|webp)$/ }, args => ({ contents: `export default ${JSON.stringify(`dogs/${basename(args.path)}`)}`, loader: 'js' }))
    },
  }],
})
const { sampleStores, sampleDogs } = await import(pathToFileURL(outfile))
rmSync(dir, { recursive: true })

const text = v => (v === undefined || v === null ? 'null' : `'${String(v).replaceAll('\'', '\'\'')}'`)
const json = v => (v === undefined || v === null ? 'null' : `${text(JSON.stringify(v))}::jsonb`)

const stores = sampleStores.map((s) => {
  const { id, slug, name, initials, tagline, city, area, state, founded, verified, rating, reviews, ...details } = s
  return `(${[text(id), text(slug), text(name), text(initials), text(tagline), text(city), text(area), text(state), founded, `'${verified ? 'verified' : 'in_review'}'`, rating, reviews, json(details)].join(', ')})`
})

const dogs = sampleDogs.map((d) => {
  const owner = `(select id from public.stores where public_id = ${text(d.storeId)})`
  const property = `'{${d.property.join(',')}}'::public.property_type[]`
  return `(${[text(d.fileNo), owner, text(d.name), text(d.breed), text(d.sex), text(d.city), text(d.age), d.weightKg, text(d.hips), d.level, d.priceNaira, `'${d.status}'`, text(d.photo), property, d.safeWithChildren, json(d.file)].join(', ')})`
})

// Upsert on the public ids so the seed can be re-run against a database that already has it
const storeCols = ['public_id', 'slug', 'name', 'initials', 'tagline', 'city', 'area', 'state', 'founded', 'status', 'rating', 'reviews_count', 'details']
const dogCols = ['file_no', 'store_id', 'name', 'breed', 'sex', 'city', 'age', 'weight_kg', 'hips', 'level', 'price_naira', 'status', 'photo_path', 'property', 'safe_with_children', 'file']
const upsert = (table, cols, key, rows) => `insert into public.${table} (${cols.join(', ')}) values
${rows.join(',\n')}
on conflict (${key}) do update set ${cols.filter(c => c !== key).map(c => `${c} = excluded.${c}`).join(', ')};`

writeFileSync(join(root, 'supabase/seed.sql'), `-- Generated by \`npm run db:seed\` from app/utils/stores.ts and dogs.ts. Development data only: don't edit by hand.
${upsert('stores', storeCols, 'public_id', stores)}

${upsert('dogs', dogCols, 'file_no', dogs)}
`)
console.log(`supabase/seed.sql: ${stores.length} stores, ${dogs.length} dogs`)
