// Writes supabase/seed.sql from the app's sample stores, dogs and care providers, so the database starts with
// the same marketplace the site shows today. Run with `npm run db:seed`. Development data only.
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { basename, join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { build } from 'esbuild'

const root = resolve(import.meta.dirname, '..')
const dir = mkdtempSync(join(tmpdir(), 'dogeash-seed-'))
const outfile = join(dir, 'data.mjs')

await build({
  stdin: { contents: `export { sampleStores } from './app/utils/stores'\nexport { sampleDogs } from './app/utils/dogs'\nexport { sampleCareProviders, careProviderSlug } from './app/utils/care'`, resolveDir: root, loader: 'ts' },
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile,
  logLevel: 'silent',
  alias: { '@': join(root, 'app'), '~': join(root, 'app') },
  // Vite-only: dogs.ts looks up bundled photos with it, which the seed doesn't need
  define: { 'import.meta.glob': '__noGlob' },
  banner: { js: 'const __noGlob = () => ({});' },
  plugins: [{
    // Photos become their storage path instead of a bundled file
    name: 'photo-paths',
    setup(b) {
      b.onLoad({ filter: /\.(jpe?g|png|webp)$/ }, args => ({ contents: `export default ${JSON.stringify(`dogs/${basename(args.path)}`)}`, loader: 'js' }))
    },
  }],
})
const { sampleStores, sampleDogs, sampleCareProviders, careProviderSlug } = await import(pathToFileURL(outfile))
rmSync(dir, { recursive: true })

const text = v => (v === undefined || v === null ? 'null' : `'${String(v).replaceAll('\'', '\'\'')}'`)
const json = v => (v === undefined || v === null ? 'null' : `${text(JSON.stringify(v))}::jsonb`)

const stores = sampleStores.map((s) => {
  // The care team goes in store_care_links, not details
  const { id, slug, name, initials, tagline, city, area, state, founded, verified, rating, reviews, care: _care, ...details } = s
  return `(${[text(id), text(slug), text(name), text(initials), text(tagline), text(city), text(area), text(state), founded, `'${verified ? 'verified' : 'in_review'}'`, rating, reviews, json(details)].join(', ')})`
})

const dogs = sampleDogs.map((d) => {
  const owner = `(select id from public.stores where public_id = ${text(d.storeId)})`
  const property = `'{${d.property.join(',')}}'::public.property_type[]`
  return `(${[text(d.fileNo), owner, text(d.name), text(d.breed), text(d.sex), text(d.city), text(d.age), d.weightKg, text(d.hips), d.level, d.priceNaira, `'${d.status}'`, text(d.photo), property, d.safeWithChildren, json(d.file)].join(', ')})`
})

const providers = sampleCareProviders.map(p =>
  `(${[text(p.id), text(careProviderSlug(p)), text(p.name), text(p.person), `'${p.type}'`, text(p.city), text(p.areas), p.homeVisits, p.verified, text(p.credential), p.rating, p.reviews, p.priceFrom].join(', ')})`)

const links = sampleStores.flatMap(s => s.care.map(c =>
  `((select id from public.stores where public_id = ${text(s.id)}), (select id from public.care_providers where public_id = ${text(c.providerId)}), ${text(c.relationship)})`))

// Upsert on the public ids so the seed can be re-run against a database that already has it
const storeCols = ['public_id', 'slug', 'name', 'initials', 'tagline', 'city', 'area', 'state', 'founded', 'status', 'rating', 'reviews_count', 'details']
const providerCols = ['public_id', 'slug', 'name', 'person', 'type', 'city', 'areas', 'home_visits', 'verified', 'credential', 'rating', 'reviews_count', 'price_from']
const dogCols = ['file_no', 'store_id', 'name', 'breed', 'sex', 'city', 'age', 'weight_kg', 'hips', 'level', 'price_naira', 'status', 'photo_path', 'property', 'safe_with_children', 'file']
const upsert = (table, cols, key, rows) => `insert into public.${table} (${cols.join(', ')}) values
${rows.join(',\n')}
on conflict (${key}) do update set ${cols.filter(c => c !== key).map(c => `${c} = excluded.${c}`).join(', ')};`

writeFileSync(join(root, 'supabase/seed.sql'), `-- Generated by \`npm run db:seed\` from app/utils/stores.ts, dogs.ts and care.ts. Development data only: don't edit by hand.
${upsert('stores', storeCols, 'public_id', stores)}

${upsert('dogs', dogCols, 'file_no', dogs)}

${upsert('care_providers', providerCols, 'public_id', providers)}

insert into public.store_care_links (store_id, provider_id, relationship) values
${links.join(',\n')}
on conflict (store_id, provider_id) do update set relationship = excluded.relationship;
`)
console.log(`supabase/seed.sql: ${stores.length} stores, ${dogs.length} dogs, ${providers.length} care providers, ${links.length} care links`)
